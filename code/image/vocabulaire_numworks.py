def afficher(x0=0, y0=0, t=2):
    HEXV = "0123456789ABCDEF"
    n = 0
    for k in range(0, len(DATA), 2):
        couleur = PALETTE[HEXV.find(DATA[k])]
        for _ in range(HEXV.find(DATA[k+1]) + 1):
            x = x0 + (n % LARGEUR) * t
            y = y0 + (n // LARGEUR) * t
            for dx in range(t):
                for dy in range(t):
                    set_pixel(x + dx, y + dy, couleur)
            n += 1

